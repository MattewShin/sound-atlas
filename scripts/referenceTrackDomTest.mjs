import assert from 'node:assert/strict'
import React from 'react'
import { JSDOM } from 'jsdom'
import { tracks } from '../src/data/musicData.js'
import { formatTrackTitle } from '../src/data/emotions.js'

export async function verifyReferenceTrackInteractions(App) {
  const dom = new JSDOM('<div id="root"></div>', { url: 'http://localhost' })
  const names = ['window', 'document', 'navigator', 'HTMLElement', 'IS_REACT_ACT_ENVIRONMENT', 'fetch']
  const original = new Map(names.map((name) => [name, Object.getOwnPropertyDescriptor(globalThis, name)]))
  for (const name of ['window', 'document', 'navigator', 'HTMLElement']) Object.defineProperty(globalThis, name, { value: name === 'window' ? dom.window : dom.window[name], configurable: true, writable: true })
  globalThis.IS_REACT_ACT_ENVIRONMENT = true
  let requests = 0
  globalThis.fetch = async () => { requests++; throw new Error('Reference search must stay local') }
  dom.window.scrollTo = () => {}
  dom.window.requestAnimationFrame = (callback) => dom.window.setTimeout(callback, 0)
  const doc = dom.window.document
  const flush = async (action) => React.act(async () => { action?.(); await new Promise((resolve) => setTimeout(resolve, 10)) })
  const button = (label) => [...doc.querySelectorAll('button')].find((node) => (node.getAttribute('aria-label') || node.textContent.trim()) === label)
  const click = async (node) => { assert.ok(node, '선택할 요소 존재'); await flush(() => node.click()) }
  const chooseLevel = async (index) => {
    const toggle = doc.querySelector('.exploration-level-switch')
    if (toggle.getAttribute('aria-checked') !== String(index === 1)) await click(toggle)
  }
  const discoveryIds = () => [...doc.querySelectorAll('.reference-discovery .mini-track')].map((node) => node.dataset.trackId)
  const relatedIds = () => [...doc.querySelectorAll('.similar-section .mini-track')].map((node) => node.dataset.trackId)
  const featuredId = () => doc.querySelector('.featured-track')?.dataset.featuredTrackId
  const search = async (value) => flush(() => {
    const input = doc.querySelector('#reference-search')
    Object.getOwnPropertyDescriptor(dom.window.HTMLInputElement.prototype, 'value').set.call(input, value)
    input.dispatchEvent(new dom.window.Event('input', { bubbles: true }))
  })
  const key = async (value, options = {}) => flush(() => doc.querySelector('#reference-search').dispatchEvent(new dom.window.KeyboardEvent('keydown', { key: value, bubbles: true, cancelable: true, ...options })))
  const assertOnlyTextSearch = () => {
    assert.equal(doc.querySelector('.featured-track'), null, '입력 중 이전 대표 카드 숨김')
    assert.equal(doc.querySelector('.similar-section'), null, '입력 중 유사곡 카드 숨김')
    assert.equal(doc.querySelector('.starter-carousel'), null, '입력 중 랜덤 카드 숨김')
    assert.equal(doc.querySelector('.reference-suggestions img'), null, '자동완성은 이미지 없는 텍스트')
    assert.equal(doc.querySelector('.reference-suggestions button'), null, '곡마다 상세/추천 버튼을 만들지 않음')
    assert.equal(button('상세 보기'), undefined)
    assert.equal(doc.querySelector('.track-detail-backdrop.is-open'), null)
  }
  let root
  try {
    const { createRoot } = await import('react-dom/client')
    root = createRoot(doc.getElementById('root'))
    await flush(() => root.render(React.createElement(App)))
    assert.ok(doc.querySelector('.mood-section'))
    assert.equal(doc.querySelector('.exploration-level-switch').getAttribute('role'), 'switch')
    await click(button('평안한'))
    await chooseLevel(1)
    assert.equal(doc.querySelector('#reference-search').getAttribute('placeholder'), null)
    assert.equal(doc.querySelector('#reference-search').getAttribute('role'), 'combobox')
    assert.equal(doc.querySelector('#reference-search').getAttribute('aria-expanded'), 'false')
    assert.equal(doc.querySelector('#reference-discovery-title').textContent, '오늘은 이런곡이 어떤가요?')
    const firstDiscovery = discoveryIds()
    assert.equal(firstDiscovery.length, 4)
    assert.equal(new Set(firstDiscovery).size, 4)
    assert.equal(doc.querySelector('.reference-explorer .recommendation-mode-control'), null)
    await click(button('보관함'))
    await click(button('음악 탐색'))
    assert.ok(discoveryIds().every((id) => !firstDiscovery.includes(id)), '홈 재진입 시 랜덤 곡 교체')
    const discoveryTrack = discoveryIds()[0]
    await click(doc.querySelector('.reference-discovery .mini-track'))
    assert.equal(featuredId(), discoveryTrack, '랜덤 카드도 상세 대신 대표 카드로 선택')
    assert.equal(doc.querySelector('.track-detail-backdrop.is-open'), null)
    await click(button('기준곡 변경'))
    assert.equal(doc.activeElement.id, 'reference-search')
    await search('Chopin')
    assertOnlyTextSearch()
    assert.equal(doc.querySelectorAll('[role="option"]').length, 20)
    assert.equal(doc.querySelector('#reference-search').getAttribute('aria-expanded'), 'true')
    await click(button('검색 결과 더 보기'))
    assert.equal(doc.querySelectorAll('[role="option"]').length, 40)
    await key('Enter')
    assert.equal(featuredId(), undefined, '모호한 다중 결과를 첫 Enter로 임의 확정하지 않음')
    await search('없는곡')
    assert.equal(doc.querySelectorAll('[role="option"]').length, 0)
    assert.ok(doc.querySelector('.reference-search-results').textContent.includes('등록된 곡을 찾지 못했어요'))
    await search('쇼팽 발라드 4번')
    assertOnlyTextSearch()
    assert.equal(doc.querySelectorAll('[role="option"]').length, 1)
    await key('Enter', { isComposing: true })
    assert.equal(featuredId(), undefined, '한글 조합 중 Enter는 검색을 확정하지 않음')
    await key('Enter', { keyCode: 229 })
    assert.equal(featuredId(), undefined, 'IME keyCode 229도 검색을 확정하지 않음')
    await key('Enter')
    const source = 'chopin-ballade-op52-no4'
    assert.equal(featuredId(), source)
    assert.equal(doc.querySelector('.reference-suggestions'), null)
    assert.equal(doc.querySelector('#reference-search').getAttribute('aria-expanded'), 'false')
    assert.equal(doc.querySelector('.reference-featured-section .section-heading p').textContent, 'FOR YOU')
    assert.equal(button('검색 음악').getAttribute('aria-pressed'), 'true')
    assert.equal(button('내 취향').disabled, true)
    assert.equal(doc.querySelector('.similar-section .section-heading p').textContent, 'MORE TO EXPLORE')
    assert.equal(doc.querySelector('.similar-section h2').textContent, '비슷한 결의 음악')
    assert.ok(!doc.querySelector('.reference-explorer').textContent.includes('이 곡과 비슷한'))
    assert.ok(relatedIds().length > 0 && relatedIds().length <= 8)
    assert.ok(!relatedIds().includes(source))
    await search('Chopin Op.52')
    assertOnlyTextSearch()
    await key('Escape')
    assert.equal(featuredId(), source, 'Escape는 이전 대표 카드 복원')
    await search('Chopin Op.52')
    await click(doc.querySelector('[role="option"]'))
    assert.equal(featuredId(), source, '텍스트 후보 클릭도 상세 대신 대표 카드 확정')
    assert.equal(doc.querySelector('.track-detail-backdrop.is-open'), null)
    await click(doc.querySelector('.featured-track .track-card-top button'))
    assert.equal(doc.querySelector('.featured-track .track-card-top button').getAttribute('aria-pressed'), 'true')
    await click(doc.querySelector('.featured-track .play-button'))
    assert.ok(doc.querySelector('.highlight-short-backdrop.is-open'))
    await click(doc.querySelector('.highlight-short-top button'))
    const recommended = relatedIds()[0]
    await click(doc.querySelector('.similar-section .mini-track'))
    assert.equal(featuredId(), recommended, '유사곡은 대표 카드로 올림')
    assert.equal(doc.querySelector('.track-detail-backdrop.is-open'), null, '유사곡 선택으로 상세를 직접 열지 않음')
    assert.ok(!relatedIds().includes(recommended), '현재 대표곡은 가로 추천에서 제외')
    await click(doc.querySelector('.featured-track .track-card-top button'))
    await click(doc.querySelector('.featured-track'))
    assert.ok(doc.querySelector('.track-detail-backdrop.is-open'), '대표 카드 클릭으로만 상세 열기')
    assert.ok(doc.querySelector('.music-journal'), '기존 비공개 기록 연결')
    await click(doc.querySelector('button[aria-label="곡 상세 닫기"]'))
    await click(button('검색 음악'))
    assert.equal(featuredId(), source)
    const listIds = relatedIds()
    await click(button('추천곡 더 보기 →'))
    assert.ok(doc.querySelector('.recommendation-list'), '공통 전체 추천 목록 연결')
    assert.deepEqual([...doc.querySelectorAll('.recommendation-track-open strong')].map((node) => node.textContent), listIds.map((id) => {
      const track = tracks.find((track) => track.id === id)
      return formatTrackTitle(track) + (track.alias ? ` [${track.alias}]` : '')
    }))
    await click(doc.querySelector('.recommendation-track-open'))
    assert.equal(featuredId(), listIds[0], '전체 목록 선택도 상세 대신 대표 카드로 복귀')
    assert.equal(doc.querySelector('.track-detail-backdrop.is-open'), null)
    await click(button('내 취향'))
    assert.ok(doc.querySelector('.featured-track .library-recommendation-label'))
    assert.equal(doc.querySelector('.exploration-level-switch').getAttribute('aria-checked'), 'true')
    assert.ok(![source, recommended].includes(featuredId()))
    await chooseLevel(0)
    assert.equal(button('평안한').getAttribute('aria-pressed'), 'true')
    await chooseLevel(1)
    assert.equal(button('내 취향').getAttribute('aria-pressed'), 'true')
    await click(button('검색 음악'))
    assert.equal(featuredId(), source)
    await click(doc.querySelector('.featured-track .track-card-top button'))
    await click(doc.querySelector(`.similar-section [data-track-id="${recommended}"]`))
    await click(doc.querySelector('.featured-track .track-card-top button'))
    assert.equal(button('내 취향').disabled, true, '마지막 보관 해제 시 취향 상태 정리')
    assert.equal(featuredId(), recommended, '검색 음악에서 마지막 보관 해제도 선택한 대표곡 유지')
    await click(doc.querySelector('.featured-track .track-card-top button'))
    await click(button('기준곡 변경'))
    await search('Chopin Sonata No.2')
    assert.equal(doc.querySelectorAll('[role="option"]').length, 4)
    await key('ArrowDown')
    await key('ArrowDown')
    const highlighted = doc.querySelector('[role="option"][aria-selected="true"]')
    assert.equal(doc.querySelector('#reference-search').getAttribute('aria-activedescendant'), highlighted.id)
    const movement = highlighted.dataset.searchTrackId
    await key('Enter')
    assert.equal(featuredId(), movement)
    assert.ok(relatedIds().every((id) => !id.startsWith('chopin-sonata-op35-no2-')))
    await click(button('보관함'))
    assert.ok([...doc.querySelectorAll('.saved-track-copy strong')].some((node) => node.textContent.startsWith(formatTrackTitle(tracks.find(({ id }) => id === recommended)))))
    assert.equal(requests, 0, '검색·선택·로컬 보관에 외부 호출 없음')
  } finally {
    if (root) await flush(() => root.unmount())
    dom.window.close()
    for (const [name, descriptor] of original) { if (descriptor) Object.defineProperty(globalThis, name, descriptor); else delete globalThis[name] }
  }
}
