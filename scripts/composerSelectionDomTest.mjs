import assert from 'node:assert/strict'
import React from 'react'
import { JSDOM } from 'jsdom'
import { tracks } from '../src/data/musicData.js'
import { formatTrackTitle } from '../src/data/emotions.js'
import { getComposerOptions } from '../src/data/composerSelection.js'
import { getRecommendationResult } from '../src/data/recommendations.js'
import { STORAGE_KEY } from '../src/data/storage.js'

export async function verifyComposerSelectionInteractions(App) {
  const dom = new JSDOM('<div id="root"></div>', { url: 'http://localhost' })
  const names = ['window', 'document', 'navigator', 'HTMLElement', 'IS_REACT_ACT_ENVIRONMENT', 'fetch']
  const original = new Map(names.map((name) => [name, Object.getOwnPropertyDescriptor(globalThis, name)]))
  for (const name of ['window', 'document', 'navigator', 'HTMLElement']) Object.defineProperty(globalThis, name, { value: name === 'window' ? dom.window : dom.window[name], configurable: true, writable: true })
  globalThis.IS_REACT_ACT_ENVIRONMENT = true
  globalThis.fetch = async () => { throw new Error('Composer selection must not request concert data') }
  dom.window.scrollTo = () => {}
  dom.window.requestAnimationFrame = (callback) => dom.window.setTimeout(callback, 0)
  dom.window.localStorage.setItem(STORAGE_KEY, JSON.stringify({ [tracks[0].id]: { listenAgain: true } }))
  const doc = dom.window.document
  const flush = async (action) => React.act(async () => { action?.(); await new Promise((resolve) => setTimeout(resolve, 10)) })
  const button = (label) => [...doc.querySelectorAll('button')].find((node) => node.textContent.trim() === label)
  const click = async (node) => { assert.ok(node, '조작할 버튼 존재'); await flush(() => node.click()) }
  const clickLabel = async (label) => click(button(label))
  const trigger = () => doc.querySelector('.composer-trigger')
  const option = (name) => [...doc.querySelectorAll('.composer-options button')].find((node) => node.querySelector('span').textContent === name)
  const checked = (name) => option(name).getAttribute('aria-checked') === 'true'
  const search = async (query) => flush(() => {
    const input = doc.querySelector('.composer-search input')
    Object.getOwnPropertyDescriptor(dom.window.HTMLInputElement.prototype, 'value').set.call(input, query)
    input.dispatchEvent(new dom.window.Event('input', { bubbles: true }))
  })
  const escape = async () => flush(() => doc.dispatchEvent(new dom.window.KeyboardEvent('keydown', { key: 'Escape', bubbles: true, cancelable: true })))
  const tab = async (shiftKey = false) => flush(() => doc.dispatchEvent(new dom.window.KeyboardEvent('keydown', { key: 'Tab', shiftKey, bubbles: true, cancelable: true })))
  const featured = () => doc.querySelector('.featured-track')?.outerHTML
  const selectedTags = () => [...doc.querySelectorAll('.composer-tags li > span')].map((node) => node.textContent)
  const apply = async (names) => {
    await click(trigger()); await clickLabel('초기화')
    for (const name of names) await click(option(name))
    await clickLabel('적용')
  }
  let root
  try {
    const { createRoot } = await import('react-dom/client')
    root = createRoot(doc.getElementById('root'))
    await flush(() => root.render(React.createElement(React.StrictMode, null, React.createElement(App))))
    assert.equal(trigger().textContent, '작곡가 · 전체⌄')
    assert.ok(doc.querySelector('.starter-carousel'), '보관함이 있어도 최초 모드는 변경하지 않음')
    const initial = doc.querySelector('.starter-carousel').outerHTML
    await click(trigger())
    assert.equal(doc.activeElement, doc.querySelector('.composer-search input'))
    assert.equal(doc.body.style.overflow, 'hidden')
    assert.ok(doc.querySelector('.app-shell').hasAttribute('inert'))
    assert.deepEqual([...doc.querySelectorAll('.composer-options button > span:first-child')].map((node) => node.textContent), getComposerOptions(tracks))
    await search(' CHOPIN ')
    assert.equal(doc.querySelectorAll('.composer-options button').length, 1)
    await click(option('쇼팽'))
    assert.ok(checked('쇼팽'))
    await search('없는이름')
    assert.ok(doc.querySelector('.composer-no-results').textContent.includes('검색한 작곡가가 없어요.'))
    await search('')
    await click(option('베토벤')); await click(option('브람스'))
    assert.ok(doc.querySelector('.composer-footer').textContent.includes('3 / 3명 선택'))
    assert.ok(doc.querySelector('.composer-limit').textContent.includes('최대 3명까지 선택할 수 있어요.'))
    assert.equal(option('슈만').disabled, true)
    await click(option('슈만'))
    assert.equal(checked('슈만'), false, '네 번째 선택 제한')
    await click(option('베토벤'))
    assert.equal(option('슈만').disabled, false)
    await clickLabel('초기화')
    assert.equal(doc.querySelectorAll('[role="checkbox"][aria-checked="true"]').length, 0)
    await click(option('사티'))
    await escape()
    assert.equal(doc.querySelector('[role="dialog"][aria-labelledby="composer-title"]'), null)
    assert.equal(doc.activeElement, trigger())
    assert.equal(doc.body.style.overflow, '')
    assert.equal(doc.querySelector('.app-shell').hasAttribute('inert'), false)
    assert.equal(doc.querySelector('.starter-carousel').outerHTML, initial, '취소는 기존 탐색 결과도 유지')

    await clickLabel('평안한')
    await apply(['쇼팽'])
    assert.deepEqual(selectedTags(), ['쇼팽'])
    assert.equal(button('평안한').getAttribute('aria-pressed'), 'true')
    assert.equal(doc.querySelector('.featured-track .composer').textContent, '쇼팽')
    assert.ok(doc.querySelector('.composer-result').textContent.includes('쇼팽의 곡 중 ‘평안한’ 음악'))
    const beforeCancel = featured()
    for (const method of ['close', 'backdrop', 'escape']) {
      await click(trigger())
      assert.ok(checked('쇼팽'), '다시 열면 적용된 값만 사용')
      await clickLabel('초기화')
      assert.equal(featured(), beforeCancel, '임시 초기화는 추천 조건을 바꾸지 않음')
      await click(option('브람스'))
      if (method === 'close') await click(doc.querySelector('.composer-close'))
      else if (method === 'backdrop') await click(doc.querySelector('.composer-backdrop'))
      else await escape()
      assert.equal(featured(), beforeCancel)
      assert.deepEqual(selectedTags(), ['쇼팽'])
    }
    await click(trigger())
    await flush(() => button('적용').focus()); await tab()
    assert.equal(doc.activeElement.className, 'composer-close', 'Tab은 모달 첫 요소로 순환')
    await tab(true)
    assert.equal(doc.activeElement.className, 'composer-apply', 'Shift+Tab은 마지막 요소로 순환')
    await escape()

    await clickLabel('부드러운')
    assert.deepEqual(selectedTags(), ['쇼팽'], '감정 변경은 작곡가 유지')
    await apply(['쇼팽', '베토벤', '브람스'])
    assert.equal(trigger().textContent, '작곡가 · 쇼팽 외 2명⌄')
    assert.equal(button('평안한').getAttribute('aria-pressed'), 'true')
    assert.equal(button('부드러운').getAttribute('aria-pressed'), 'true')
    const count = Number(doc.querySelector('.composer-result > span').textContent.match(/\d+/)[0])
    await clickLabel('추천곡 더 보기 →')
    assert.equal(doc.querySelector('.recommendation-list-header > strong').textContent, `총 ${count}곡`)
    while (button('더 불러오기') || doc.querySelector('.recommendations-load-more')) await click(doc.querySelector('.recommendations-load-more'))
    const listed = [...doc.querySelectorAll('.recommendation-list-card .saved-track-copy > b')].map((node) => node.textContent)
    assert.equal(listed.length, count, '안내 숫자와 실제 전체 결과 집합 일치')
    assert.ok(listed.every((name) => ['쇼팽', '베토벤', '브람스'].includes(name)))
    await clickLabel('전체 작곡가로 넓히기')
    await clickLabel('← 음악 탐색으로')
    assert.equal(selectedTags().length, 0)
    assert.equal(button('평안한').getAttribute('aria-pressed'), 'true')
    assert.equal(button('부드러운').getAttribute('aria-pressed'), 'true')

    await clickLabel('내 취향')
    assert.ok(doc.querySelector('.library-recommendation-label'))
    await apply(['베토벤'])
    assert.equal(doc.querySelector('.library-recommendation-label'), null, '작곡가 적용은 직접 조건 추천으로 전환')
    await clickLabel('내 취향')
    assert.equal(doc.querySelector('.featured-track .composer').textContent, '베토벤', '명시적으로 취향 모드에 재진입해도 작곡가 범위 유지')
    assert.ok(doc.querySelector('.composer-mode-guide'))
    const libraryBeforeCancel = featured()
    await click(trigger()); await clickLabel('초기화'); await escape()
    assert.equal(featured(), libraryBeforeCancel, '취향 모드에서도 임시 선택 취소는 모드와 결과 유지')
    await clickLabel('평안한')
    assert.equal(doc.querySelector('.library-recommendation-label'), null, '감정 직접 변경은 조건 추천으로 전환')
    assert.deepEqual(selectedTags(), ['베토벤'])
    await clickLabel('내 취향')
    await clickLabel('기분에서 시작하기')
    await clickLabel('차분한')
    assert.equal(doc.querySelector('.library-recommendation-label'), null)
    assert.deepEqual(selectedTags(), ['베토벤'])
    await apply(['쇼팽'])
    assert.equal(button('차분한').getAttribute('aria-pressed'), 'true', '작곡가 변경은 기분 선택도 유지')
    await clickLabel('선택 초기화')
    assert.deepEqual(selectedTags(), [], '기분 탭의 선택 초기화는 작곡가도 해제')
    assert.equal(button('차분한').getAttribute('aria-pressed'), 'false')
    assert.ok(doc.querySelector('.starter-carousel'), '기분과 작곡가를 함께 초기화하면 기본 탐색으로 복귀')
    await clickLabel('느낌으로 시작하기'); await clickLabel('선택 초기화')
    await apply(['사티'])
    assert.equal(doc.querySelector('.featured-track .composer').textContent, '사티')
    const orderedSatie = getRecommendationResult(tracks.filter(({ composer }) => composer === '사티')).tracks
    assert.ok(doc.querySelector('.featured-track h2').textContent.startsWith(formatTrackTitle(orderedSatie[0])), '작곡가만 선택하면 기존 ID 기본 정렬')
    assert.ok(doc.querySelector('.composer-result').textContent.includes('추천 3곡'))
    await clickLabel('힘찬')
    assert.equal(doc.querySelector('.featured-track'), null)
    assert.ok(doc.querySelector('.composer-result').textContent.includes('추천 0곡'))
    assert.ok(doc.querySelector('.track-section .library-empty'))
    await clickLabel('전체 작곡가로 넓히기')
    assert.equal(button('힘찬').getAttribute('aria-pressed'), 'true', '빈 결과에서도 넓히기는 감정 유지')
    assert.ok(doc.querySelector('.featured-track'))
    await clickLabel('선택 초기화')
    await apply(['사티'])
    await click(doc.querySelector('[aria-label="사티 선택 해제"]'))
    assert.ok(doc.querySelector('.starter-carousel'), '마지막 작곡가와 감정 해제 시 기존 기본 탐색으로 복귀')
    await apply(['쇼팽', '베토벤'])
    await click(doc.querySelector('[aria-label="쇼팽 선택 해제"]'))
    assert.deepEqual(selectedTags(), ['베토벤'], '태그 삭제는 해당 작곡가만 해제')
    await click(trigger()); await clickLabel('초기화'); await clickLabel('적용')
    assert.ok(doc.querySelector('.starter-carousel'), '초기화 적용은 전체 작곡가로 복귀')
    await apply(['쇼팽', '베토벤', '브람스'])
    await clickLabel('평안한')
    await clickLabel('선택 초기화')
    assert.deepEqual(selectedTags(), [], '느낌 탭의 선택 초기화는 선택한 작곡가 세 명도 모두 해제')
    assert.equal(button('평안한').getAttribute('aria-pressed'), 'false')
    assert.ok(trigger().textContent.includes('작곡가 · 전체'))
    assert.ok(doc.querySelector('.starter-carousel'))
    await click(trigger())
    assert.equal(doc.querySelectorAll('[role="checkbox"][aria-checked="true"]').length, 0, '다시 열어도 작곡가 초기화가 반영됨')
    await escape()
  } finally {
    if (root) await React.act(async () => root.unmount())
    dom.window.close()
    for (const [name, descriptor] of original) { if (descriptor) Object.defineProperty(globalThis, name, descriptor); else delete globalThis[name] }
  }
}
